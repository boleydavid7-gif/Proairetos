import { readFileSync } from 'node:fs';
import { beforeEach, describe, expect, it } from 'vitest';
import { APPS, edgeBlock, registryJson, runtimeRegistry, withBlock, workerBlock } from '../../core/apps';
import { familyApps } from '../../app/family/FamilyApps';
import { appDetails } from '../../app/family/appDetails';
import { handleWaitlistRequest } from '../../../worker/waitlist';
import { resetRateLimit } from '../../../worker/safeFetch';
import { SPECULATION_RULES } from '../../../worker/speculation';

/*
 * Wave 2. The copies of the manifest that code outside TypeScript reads are generated by `npm run apps:build`.
 * These tests fail while any copy is out of date, and hold what the copies say to what the hand-written lists said.
 */
const read = (path: string) => readFileSync(path, 'utf8');

describe('generated copies are current', () => {
  it('registry.generated.json', () => {
    expect(read('src/core/apps/registry.generated.json')).toBe(registryJson());
  });
  it('the service worker block', () => {
    const sw = read('public/sw.js');
    expect(withBlock(sw, workerBlock())).toBe(sw);
  });
  it('the reminder function block', () => {
    const edge = read('supabase/functions/send-reminders/index.ts');
    expect(withBlock(edge, edgeBlock())).toBe(edge);
  });
  it('a change to the manifest makes a copy out of date', () => {
    const changed = APPS.map((app) => (app.id === 'ktema' ? { ...app, name: 'Ktema 2' } : app));
    expect(workerBlock(runtimeRegistry(changed))).not.toBe(workerBlock());
  });
});

describe('the registry says what the lists written by hand said', () => {
  const registry = runtimeRegistry();
  const same = (a: readonly string[], b: readonly string[]) => expect([...a].sort()).toEqual([...b].sort());
  it('every app address the worker knows', () => {
    same(registry.appPaths, ['/askesis/', '/soma/', '/oikonomia/', '/hydros/', '/praxis/', '/theoria/', '/diaita/', '/philia/', '/ergon/', '/therapeia/', '/dynamis/', '/ktema/', '/phyton/', '/poreia/', '/mneme/', '/melete/']);
  });
  it('the windows told apart from Proairetos (Mneme was never in this list)', () => {
    same(registry.windowPaths, ['/askesis/', '/soma/', '/oikonomia/', '/hydros/', '/praxis/', '/theoria/', '/diaita/', '/philia/', '/ergon/', '/therapeia/', '/dynamis/', '/ktema/', '/phyton/', '/poreia/', '/melete/']);
  });
  it('notice names (a retired app wears Theoria’s name in the worker, its own on an iPhone push)', () => {
    expect(registry.noticeNames).toEqual({ proairetos: 'Proairetos', askesis: 'Askesis', oikonomia: 'Oikonomia', hydros: 'Hydros', praxis: 'Theoria', diaita: 'Diaita', philia: 'Philia', ergon: 'Ergon', therapeia: 'Therapeia', dynamis: 'Dynamis', ktema: 'Ktema', phyton: 'Phyton', poreia: 'Poreia', melete: 'Meletē' });
    expect(registry.pushNames).toEqual({ ...registry.noticeNames, praxis: 'Praxis' });
  });
  it('push icons (Poreia keeps its drawn icon)', () => {
    expect(registry.pushIcons.poreia).toBe('/poreia/icon.svg');
    expect(registry.pushIcons.proairetos).toBe('/icons/icon-192.png');
    expect(registry.pushIcons.ktema).toBe('/ktema/icons/icon-192.png');
  });
  it('the apps whose tap opens their own page the common way', () => {
    same(registry.genericTap, ['diaita', 'philia', 'ergon', 'therapeia', 'dynamis', 'ktema', 'phyton', 'poreia', 'melete']);
  });
  it('the service worker answers as it did', () => {
    const sw = read('public/sw.js');
    const block = sw.slice(sw.indexOf('const REGISTRY'), sw.indexOf('// END GENERATED REGISTRY'));
    const from = (start: string) => sw.slice(sw.indexOf(start), sw.indexOf('\n}\n', sw.indexOf(start)) + 2);
    const run = new Function(`${block}\nconst APP_NAMES = REGISTRY.noticeNames;\n${from('function appFor(open)')}\n${from('function appNameFor')}\n${from('function iconFor')}\nreturn { appFor, appNameFor, iconFor };`)() as { appFor(o: string): string; appNameFor(o: string): string; iconFor(o: string): string };
    const expected: [string, string, string][] = [
      ['askesis:workout:1', 'Askesis', '/askesis/icons/icon-192.png'],
      ['oikonomia:bill:2', 'Oikonomia', '/oikonomia/icons/icon-192.png'],
      ['hydros', 'Hydros', '/hydros/icons/icon-192.png'],
      ['praxis:x', 'Theoria', '/theoria/icons/icon-192.png'],
      ['melete:subject:3', 'Meletē', '/melete/icons/icon-192.png'],
      ['poreia', 'Poreia', '/poreia/icons/icon-192.png'],
      ['soma:recipe:1', 'Proairetos', '/icons/icon-192.png'],
      ['mneme', 'Proairetos', '/icons/icon-192.png'],
      ['today', 'Proairetos', '/icons/icon-192.png'],
    ];
    for (const [open, name, icon] of expected) {
      expect(run.appNameFor(open), open).toBe(name);
      expect(run.iconFor(open), open).toBe(icon);
    }
  });
});

describe('display facts are as they were', () => {
  it('the family list leaves Praxis out and keeps every name, address, icon, line and color', () => {
    expect(familyApps.map((app) => app.id)).toEqual(['proairetos', 'askesis', 'hydros', 'soma', 'oikonomia', 'poreia', 'theoria', 'diaita', 'philia', 'ergon', 'therapeia', 'dynamis', 'ktema', 'phyton', 'mneme', 'melete']);
    expect(familyApps).toMatchSnapshot();
  });
  it('the Store details', () => {
    expect(appDetails).toMatchSnapshot();
  });
});

describe('the worker lists', () => {
  beforeEach(() => resetRateLimit());
  it('prefetch covers the same apps', () => {
    const rule = SPECULATION_RULES.prefetch[0].where.or.map((each) => each.href_matches);
    same(rule, ['/', ...['askesis', 'soma', 'oikonomia', 'hydros', 'poreia', 'praxis', 'theoria', 'diaita', 'philia', 'ergon', 'therapeia', 'dynamis', 'ktema', 'phyton'].map((a) => `/${a}/*`)]);
  });
  it('the waitlist accepts the same apps and Noesis', async () => {
    const seen: string[][] = [];
    const fetcher = (async (_url: string, init: RequestInit) => {
      seen.push((JSON.parse(String(init.body)) as { apps: string[] }).apps);
      return new Response('true');
    }) as unknown as typeof fetch;
    const names = ['proairetos', 'askesis', 'soma', 'oikonomia', 'hydros', 'poreia', 'praxis', 'theoria', 'diaita', 'philia', 'ergon', 'therapeia', 'dynamis', 'ktema', 'phyton', 'noesis', 'mneme', 'melete'];
    const body = new URLSearchParams([['email', 'a@b.co'], ...names.map((name) => ['apps', name] as [string, string])]);
    await handleWaitlistRequest(new Request('https://proairetos.com/api/waitlist', { method: 'POST', body, headers: { 'content-type': 'application/x-www-form-urlencoded', origin: 'https://proairetos.com' } }), { SUPABASE_URL: 'https://x.supabase.co', SUPABASE_ANON_KEY: 'k' }, fetcher);
    same(seen[0], names.filter((name) => name !== 'mneme' && name !== 'melete'));
  });
});

function same(a: readonly string[], b: readonly string[]) {
  expect([...a].sort()).toEqual([...b].sort());
}
