/*
 * Builds src/soma/core/nutritionTable.ts from USDA SR28 (public domain; the copy in the npm package
 * fda-nutrient-database, data/ABBREV.txt). Run: node scripts/nutrition/build.mjs path/to/ABBREV.txt
 * Keeps per 100 g: kcal, protein, fat, saturated fat, carbohydrate, sugars, fibre, sodium; and the
 * household weights SR28 gives ("1 cup" = 240 g) so cups and spoons turn into grams.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { FOODS } from './foods.mjs';

const path = process.argv[2];
const rows = readFileSync(path, 'latin1').split(/\r?\n/).filter(Boolean).map((line) => line.split('^').map((field) => field.replace(/^~|~$/g, '')));
const num = (value) => (value === '' || value === undefined ? undefined : Number(value));
// ABBREV columns (SR28 documentation, p. 44)
const COL = { ndb: 0, desc: 1, kcal: 3, protein: 4, fat: 5, carbs: 7, fibre: 8, sugar: 9, sodium: 15, sat: 44, gm1: 48, desc1: 49, gm2: 50, desc2: 51 };

const out = [];
const problems = [];
for (const [key, match, sr, extra = {}] of FOODS) {
  // The exact description only: a near match picked the salted, smoked almonds once.
  const row = rows.find((r) => r[COL.desc] === sr);
  if (!row) {
    problems.push(`${key}: no SR28 food "${sr}"`);
    continue;
  }
  const measures = [];
  for (const [g, d] of [[COL.gm1, COL.desc1], [COL.gm2, COL.desc2]]) {
    const grams = num(row[g]);
    const words = row[d];
    const unit = words?.match(/^([\d.\/ ]+)\s*(cup|tbsp|tsp|fl oz)\b/i);
    if (grams && unit) {
      const amount = unit[1].trim().split(' ').reduce((sum, part) => sum + (part.includes('/') ? Number(part.split('/')[0]) / Number(part.split('/')[1]) : Number(part)), 0);
      const perCup = { cup: 1, tbsp: 16, tsp: 48, 'fl oz': 8 }[unit[2].toLowerCase()];
      if (amount > 0) measures.push(Math.round((grams / amount) * perCup));
    }
  }
  out.push({
    key,
    ndb: row[COL.ndb],
    sr: row[COL.desc],
    match: match.source,
    per100: [num(row[COL.kcal]), num(row[COL.protein]), num(row[COL.fat]), num(row[COL.sat]) ?? 0, num(row[COL.carbs]), num(row[COL.sugar]) ?? 0, num(row[COL.fibre]) ?? 0, num(row[COL.sodium]) ?? 0],
    cup: measures[0],
    ...extra,
  });
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
const lines = out.map((food) => `  { key: ${JSON.stringify(food.key)}, ndb: '${food.ndb}', match: /${food.match}/, per100: [${food.per100.join(', ')}]${food.cup ? `, cup: ${food.cup}` : ''}${food.each ? `, each: ${food.each}` : ''}${food.fvl ? ', fvl: true' : ''} }, // ${food.sr}`);
writeFileSync('src/soma/core/nutritionTable.ts', `// Generated by scripts/nutrition/build.mjs from USDA SR28 (public domain). Do not edit by hand.
// per100: kcal, protein g, fat g, saturated fat g, carbohydrate g, sugars g, fibre g, sodium mg, per 100 g.
// cup: grams in one US cup, from SR28's household weights. each: grams for one, when a recipe counts them.

export type Food = { key: string; ndb: string; match: RegExp; per100: readonly number[]; cup?: number; each?: number; fvl?: true };

export const FOODS: readonly Food[] = [
${lines.join('\n')}
];
`);
console.log(`${out.length} foods`);
for (const food of out) console.log(food.key.padEnd(20), food.sr.slice(0, 60).padEnd(62), food.per100.join(' '), food.cup ?? '');
